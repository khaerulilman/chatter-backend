/**
 * Chatter API - Merge Postman Collections
 * =========================================
 * This script reads all individual collection JSON files from the
 * collections/ directory and merges them into a single Postman
 * collection that can be imported directly into Postman.
 *
 * Usage:
 *   node merge-collections.js
 *
 * Output:
 *   Chatter-Merged.postman_collection.json
 */

import { readFileSync, readdirSync, writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const collectionsDir = join(__dirname, "collections");
const outputFile = join(__dirname, "Chatter-Merged.postman_collection.json");

// Pre-request script (collection-level)
const collectionPreRequest = [
  "// === Chatter API - Global Pre-request ===",
  "const method = pm.request.method;",
  "const url = pm.request.url.toString();",
  "console.log(`[PRE-REQUEST] ${method} ${url}`);",
  "",
  "if (!pm.environment.get('base_url')) {",
  "    pm.environment.set('base_url', 'http://localhost:3000');",
  "}",
  "",
  "if (!pm.environment.get('test_email')) {",
  "    const ts = Date.now();",
  "    pm.environment.set('test_email', `testuser_${ts}@example.com`);",
  "    pm.environment.set('test_username', `testuser_${ts}`);",
  "    pm.environment.set('test_name', `Test User ${ts}`);",
  "    pm.environment.set('test_password', 'password123');",
  "}",
];

// Post-response script (collection-level)
const collectionTestScript = [
  "// === Chatter API - Global Post-response ===",
  "const status = pm.response.code;",
  "const time = pm.response.responseTime;",
  "console.log(`[RESPONSE] Status: ${status} | Time: ${time}ms`);",
  "",
  "pm.test('Response is valid JSON', function () {",
  "    pm.response.to.be.json;",
  "});",
];

// Read all collection files
const files = readdirSync(collectionsDir).filter((f) =>
  f.endsWith(".collection.json"),
);

console.log(`Found ${files.length} collection files:`);
files.forEach((f) => console.log(`  - ${f}`));

// Build merged items
const mergedItems = [];

for (const file of files) {
  const filePath = join(collectionsDir, file);
  const content = JSON.parse(readFileSync(filePath, "utf-8"));

  // Use the collection name as the folder name
  const folderName = content.info.name.replace("Chatter - ", "");

  mergedItems.push({
    name: folderName,
    item: content.item,
    description: content.info.description || "",
  });

  console.log(`  ✓ ${folderName}: ${countRequests(content.item)} request(s)`);
}

function countRequests(items) {
  let count = 0;
  for (const item of items) {
    if (item.item) {
      count += countRequests(item.item);
    } else {
      count++;
    }
  }
  return count;
}

// Build merged collection
const mergedCollection = {
  info: {
    _postman_id: "chatter-merged-collection",
    name: "Chatter API - Full Collection",
    description:
      "Complete Chatter API collection merged from individual route collections.\nAll tests are for valid/success cases only (200/201).\n\nGenerated by merge-collections.js",
    schema:
      "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
  },
  auth: {
    type: "bearer",
    bearer: [
      {
        key: "token",
        value: "{{auth_token}}",
        type: "string",
      },
    ],
  },
  event: [
    {
      listen: "prerequest",
      script: {
        type: "text/javascript",
        exec: collectionPreRequest,
      },
    },
    {
      listen: "test",
      script: {
        type: "text/javascript",
        exec: collectionTestScript,
      },
    },
  ],
  variable: [
    {
      key: "base_url",
      value: "http://localhost:3000",
    },
  ],
  item: mergedItems,
};

// Write output
writeFileSync(outputFile, JSON.stringify(mergedCollection, null, 2), "utf-8");

const totalRequests = mergedItems.reduce(
  (sum, folder) => sum + countRequests(folder.item),
  0,
);
console.log(
  `\n✓ Merged collection written to: Chatter-Merged.postman_collection.json`,
);
console.log(`  Total folders: ${mergedItems.length}`);
console.log(`  Total requests: ${totalRequests}`);
